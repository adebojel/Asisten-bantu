import fs from "node:fs";
import assert from "node:assert/strict";
const read = (path) => fs.readFileSync(path, "utf8");
const memory = read("app/src/main/java/com/asisten/bantu/LocalMemoryStore.kt");
const secure = read("app/src/main/java/com/asisten/bantu/EncryptedLocalMemoryStore.kt");
const manifest = read("app/src/main/AndroidManifest.xml");
const runtime = read("app/src/main/java/com/asisten/bantu/LocalModelRuntimeManager.kt");
const router = read("app/src/main/java/com/asisten/bantu/OnlineAiRouter.kt");
assert.match(memory, /EncryptedLocalMemoryStore\.read/);
assert.match(memory, /EncryptedLocalMemoryStore\.write/);
assert.doesNotMatch(memory, /getSharedPreferences/);
assert.match(secure, /AES\/GCM\/NoPadding/);
assert.match(secure, /AndroidKeyStore/);
assert.match(secure, /setRandomizedEncryptionRequired\(true\)/);
assert.match(secure, /Fail closed/);
assert.match(manifest, /android:allowBackup="false"/);
assert.match(manifest, /android:usesCleartextTraffic="false"/);
assert.match(runtime, /IDLE_UNLOAD_MS = 120_000L/);
assert.match(runtime, /closeExecutor\.execute/);
assert.match(router, /AI online telah dinonaktifkan/);
assert.doesNotMatch(router, /OkHttpClient|Request\.Builder|https:\/\//);
console.log("Stage 5 security regression checks passed.");
